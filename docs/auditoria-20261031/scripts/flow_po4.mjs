import { start, stop, login, go, shot, fields, flushErrors, BASE } from './lib.mjs';
const OUT = 'out/flows'; const A = 'Compras';
await start();
const inv = await login('inventario', OUT);
await go(inv, '/purchases/requests');
const csrf = await inv.evaluate(() => document.querySelector('meta[name="csrf-token"]')?.content || '');
const prods = await (await inv.request.get(BASE + '/api/products?search=AUD-CAB')).json();
const pid = (prods.items || prods.products || prods)[0].id;
const r = await inv.request.post(BASE + '/api/replenishment-requests', { headers: { 'X-CSRFToken': csrf }, data: { items: [{ product_id: pid, quantity: 200 }], notes: 'Reposición de cable para obra grande' } });
const req = await r.json(); console.log('solicitud API', r.status(), req.request_number, req.id);
await go(inv, '/purchases/requests');
console.log('inventario ve:', (await inv.locator('tbody').innerText()).replace(/\s+/g, ' '));
const as = await login('asistente', OUT);
await go(as, '/purchases/requests');
await shot(as, 'solicitudes_asistente');
console.log('asistente ve:', (await as.locator('tbody').innerText()).replace(/\s+/g, ' ').slice(0, 400));
const row = as.locator('tbody tr', { hasText: req.request_number }).first();
await row.locator('a, button').last().click(); await as.waitForTimeout(1200);
console.log('URL detalle', as.url());
console.log((await as.locator('main').innerText()).slice(0, 2500));
console.log('botones', await as.locator('main button:visible').allInnerTexts());
await shot(as, 'detalle_solicitud');
flushErrors(as, A);
await stop(OUT);
