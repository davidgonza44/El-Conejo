import { start, stop, login, go, shot, flushErrors } from './lib.mjs';
const OUT = 'out/flows'; const A = 'Notas';
await start();
const p = await login('admin', OUT);
const stock = async () => { const r = await p.request.get('http://127.0.0.1:5099/api/products?search=AUD-CAB'); const j = await r.json(); return (j.items || j.products || j)[0]?.current_stock; };
console.log('stock antes', await stock());
await go(p, '/delivery-notes');
await p.locator('#notes-tbody tr', { hasText: 'NE-000002' }).locator('button, a').first().click(); await p.waitForTimeout(1000);
await p.click('#btn-cancel-note'); await p.waitForTimeout(500);
console.log('form anulación visible', await p.locator('#cancel-form').isVisible(), 'label botón', await p.locator('#btn-cancel-note-label').innerText());
await p.click('#btn-cancel-note'); await p.waitForTimeout(800);
console.log('sin motivo ->', await p.locator('#detail-error').innerText().catch(() => ''), '| hint', await p.locator('#d-cancel-reason-hint').innerText().catch(() => ''), 'nativo', p.audit.lastNative || '');
await shot(p, 'anular_sin_motivo', p.locator('#detail-modal'));
await p.fill('#d-cancel-reason', 'abc'); await p.click('#btn-cancel-note'); await p.waitForTimeout(800);
console.log('motivo corto ->', await p.locator('#detail-error').innerText().catch(() => ''), '| hint', await p.locator('#d-cancel-reason-hint').innerText().catch(() => ''));
await p.fill('#d-cancel-reason', 'El cliente devolvió la mercancía completa por error en el pedido.'); await p.click('#btn-cancel-note'); await p.waitForTimeout(1500);
console.log('nativo', p.audit.lastNative || '');
console.log('DETALLE ANULADA:\n' + await p.locator('#detail-modal').innerText());
await shot(p, 'anulada', p.locator('#detail-modal'));
console.log('stock después', await stock());
for (const n of flushErrors(p, A)) console.log('   ', n.slice(0, 200));
await go(p, '/inventory');
console.log((await p.locator('tbody tr').allInnerTexts()).slice(0, 4).map((r) => r.replace(/\s+/g, ' ')).join('\n'));
await p.locator('tbody tr', { hasText: 'NE-000002' }).first().locator('button, a').last().click().catch(() => {}); await p.waitForTimeout(900);
console.log('DETALLE MOV DE ANULACIÓN:\n' + await p.locator('#mv-drawer').innerText().catch(() => 'no'));
await stop(OUT);
