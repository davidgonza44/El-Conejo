import { start, stop, login, go, shot, fields, flushErrors } from './lib.mjs';
const OUT = 'out/flows'; const A = 'Compras';
await start();
const as = await login('asistente', OUT);
await go(as, '/purchases/requests/4');
const m = as.locator('main');
const save = m.getByRole('button', { name: 'Guardar cotización' });
// vacía
await save.click(); await as.waitForTimeout(800);
console.log('vacía -> nativo', as.audit.lastNative || '', '| alert', (await m.locator('[role=alert]:visible, .is-error:visible').allInnerTexts()).join('/'));
await shot(as, 'cot_vacia');
await m.locator('select[name=supplier_id]').selectOption({ index: 1 });
await m.locator('select[name=currency]').selectOption('USD'); await as.waitForTimeout(300);
console.log('etiqueta precio tras elegir USD:', await m.locator('label', { hasText: 'Precio de' }).innerText().catch(() => ''));
await m.locator('input[name=valid_until]').fill('2026-10-15');
await m.locator('input[type=number]').first().fill('2.45');
await save.click(); await as.waitForTimeout(1200);
console.log('validez pasada -> nativo', as.audit.lastNative || '', flushErrors(as, A));
await m.locator('input[name=valid_until]').fill('2026-11-30');
await m.locator('input[type=number]').first().fill('0');
await save.click(); await as.waitForTimeout(1000);
console.log('precio 0 -> ', flushErrors(as, A));
await m.locator('input[type=number]').first().fill('2.45');
await save.click(); await as.waitForTimeout(2000);
console.log('guardar ok ->', flushErrors(as, A), as.audit.lastNative || '');
await as.reload(); await as.waitForTimeout(1200);
console.log((await m.innerText()).slice(500, 3000));
console.log('botones', await m.locator('button:visible').allInnerTexts());
await shot(as, 'tras_cotizar');
await stop(OUT);
