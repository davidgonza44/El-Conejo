import { start, stop, login, go, shot, fields, flushErrors } from './lib.mjs';
const OUT = 'out/flows'; const A = 'Conciliación';
await start();
const inv = await login('inventario', OUT);
await go(inv, '/inventory');
console.log('menú inventario:', await inv.evaluate(() => [...document.querySelectorAll('#ix-sidebar a[href]')].map((a) => a.textContent.trim().replace(/\s+/g, ' ')).join(' | ')));
const ad = await login('admin', OUT);
await go(ad, '/reconciliation');
await ad.getByText('Ver detalle', { exact: true }).first().click(); await ad.waitForTimeout(1500);
const d = ad.locator('dialog[open], [role=dialog]:visible').last();
console.log('DETALLE CONC:\n' + ((await d.count()) ? (await d.innerText()) : (await ad.locator('main').innerText()).slice(0, 2500)).replace(/\n+/g, ' | ').slice(0, 2500));
await shot(ad, 'detalle_conc', (await d.count()) ? d : undefined);
await go(ad, '/reconciliation');
await ad.getByText('Conciliación manual independiente').click(); await ad.waitForTimeout(800);
const sec = ad.locator('details[open]').last();
console.log('MANUAL:\n' + (await sec.innerText()).replace(/\n+/g, ' | ').slice(0, 1500));
console.log(JSON.stringify((await fields(ad, 'details[open]')).map((f) => `${f.id || f.name}|${f.label}|${f.type}`)));
await shot(ad, 'manual', sec);
flushErrors(ad, A);
await stop(OUT);
