import { start, stop, login, go, shot, flushErrors } from './lib.mjs';
const OUT = 'out/flows'; const A = 'Recepción';
await start();
const inv = await login('inventario', OUT);
await go(inv, '/purchases/receptions');
await inv.getByRole('button', { name: 'Nueva recepción' }).click(); await inv.waitForTimeout(1000);
const d = inv.locator('dialog[open]').last();
await d.locator('select').first().selectOption({ label: 'OC-000004 - E2E Proveedor 3DFAAF' }); await inv.waitForTimeout(1000);
await d.locator('input[type=number]').first().fill('120');
await d.locator('textarea[name=notes]').fill('Llegaron 120 m en buen estado.');
await d.locator('input[type=checkbox]').check();
await d.locator('textarea[name=closure_reason]').fill('corto');
await d.getByRole('button', { name: 'Guardar recepción' }).click(); await inv.waitForTimeout(1000);
console.log('motivo corto -> abierto', await d.isVisible(), flushErrors(inv, A).map((x) => x.slice(0, 160)));
await d.locator('textarea[name=closure_reason]').fill('El proveedor solo tenía 120 metros en existencia.');
await d.getByRole('button', { name: 'Guardar recepción' }).click(); await inv.waitForTimeout(2000);
console.log('guardar -> abierto', await d.isVisible(), flushErrors(inv, A).map((x) => x.slice(0, 160)), (await inv.locator('[role=status]:visible').allInnerTexts()).join('/'));
await go(inv, '/purchases/receptions');
console.log('lista:', (await inv.locator('tbody').innerText()).replace(/\s+/g, ' '));
await inv.locator('tbody tr').first().locator('button').first().click(); await inv.waitForTimeout(1200);
const det = inv.locator('dialog[open], [role=dialog]:visible').last();
console.log('DETALLE REC (inventario):\n' + (await det.innerText()).replace(/\n+/g, ' | '));
await shot(inv, 'det_inv', det);
const ad = await login('admin', OUT);
await go(ad, '/purchases/receptions');
console.log('lista admin:', (await ad.locator('tbody').innerText()).replace(/\s+/g, ' '));
console.log('kpis admin:', (await ad.locator('main').innerText()).slice(0, 400).replace(/\n+/g, ' | '));
await ad.locator('tbody tr').first().locator('button').first().click(); await ad.waitForTimeout(1200);
const det2 = ad.locator('dialog[open], [role=dialog]:visible').last();
console.log('DETALLE REC (admin):\n' + (await det2.innerText()).replace(/\n+/g, ' | '));
await shot(ad, 'det_admin', det2);
await go(ad, '/purchases');
console.log('OC-4 en lista:', (await ad.locator('tbody tr', { hasText: 'OC-000004' }).innerText()).replace(/\s+/g, ' '));
await stop(OUT);
