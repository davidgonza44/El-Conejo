import { start, stop, login, go, shot, fields, flushErrors } from './lib.mjs';
const OUT = 'out/flows'; const A = 'Clientes';
await start();
const p = await login('vendedor', OUT);
console.log('inicio vendedor', p.url());
const links = await p.evaluate(() => [...document.querySelectorAll('#ix-sidebar a[href]')].map((a) => a.textContent.trim().replace(/\s+/g, ' ') + ' ' + a.getAttribute('href')));
console.log(links.join('\n'));
await go(p, '/sales/customers');
await shot(p, 'lista');
await p.getByRole('button', { name: /Nuevo cliente/ }).click(); await p.waitForTimeout(700);
const dlg = p.locator('dialog[open]').last();
console.log(JSON.stringify(await fields(p, 'dialog[open]')));
await shot(p, 'nuevo', dlg);
await go(p, '/delivery-notes');
await shot(p, 'notas_lista');
await p.getByRole('button', { name: /Nueva nota/ }).click(); await p.waitForTimeout(900);
console.log(JSON.stringify(await fields(p, 'dialog[open], [role=dialog]:visible')));
await shot(p, 'nota_nueva', p.locator('dialog[open], [role=dialog]:visible').last());
flushErrors(p, A);
await stop(OUT);
