import { start, stop, login, go, shot, flushErrors } from './lib.mjs';
const OUT = 'out/flows'; const A = 'Productos-proveedor';
await start();
const as = await login('asistente', OUT);
await go(as, '/products');
await as.locator('tbody tr', { hasText: 'AUD-CAB' }).first().locator('button[aria-label*="Proponer"]').click(); await as.waitForTimeout(1200);
const d = as.locator('dialog[open]').last();
const form = d.locator('.ps-add').last();
await form.locator('select').first().selectOption({ index: 1 });
const nums = form.locator('input[type=number]');
await nums.nth(0).fill('2.30'); await form.locator('select').nth(1).selectOption('USD');
await form.locator('input:not([type])').first().fill('CAB-12-PROV').catch(async () => form.locator('input[type=text]').first().fill('CAB-12-PROV'));
await nums.nth(1).fill('5'); await nums.nth(2).fill('100');
await form.locator('input[type=checkbox]').check();
await form.locator('button', { hasText: 'Agregar proveedor' }).click(); await as.waitForTimeout(1500);
console.log('tras agregar:', (await d.innerText()).match(/Proveedores del producto[\s\S]{0,500}/)?.[0].replace(/\n+/g, ' | '));
for (const n of flushErrors(as, A)) console.log(n.slice(0, 200));
await shot(as, 'tras_agregar', d);
await d.getByRole('button', { name: 'Enviar propuesta' }).click(); await as.waitForTimeout(1500);
console.log('tras enviar: abierto', await d.isVisible(), 'texto:', (await as.locator('[role=status]:visible, .toast:visible').allInnerTexts()).join(' / '));
for (const n of flushErrors(as, A)) console.log(n.slice(0, 200));
await shot(as, 'tras_enviar');
await stop(OUT);
