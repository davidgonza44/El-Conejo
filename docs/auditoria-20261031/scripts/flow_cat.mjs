import { start, stop, login, go, shot, fields, flushErrors, TAG } from './lib.mjs';
const OUT = 'out/flows'; const A = 'Categorías';
await start();
const as = await login('asistente', OUT);
await go(as, '/categories');
console.log('botones', await as.locator('main button:visible').allInnerTexts());
await shot(as, 'lista');
const nb = as.locator('main button:visible', { hasText: /Nueva categoría|Proponer/ }).first();
await nb.click(); await as.waitForTimeout(900);
const d = as.locator('dialog[open]').last();
console.log((await d.innerText()).replace(/\n+/g, ' | ').slice(0, 900));
console.log(JSON.stringify((await fields(as, 'dialog[open]')).map((f) => `${f.id || f.name}|${f.label}|${f.type}|req=${f.required}|max=${f.maxlength}|${(f.options || []).join(';')}`)));
await shot(as, 'nueva', d);
const btn = d.getByRole('button', { name: 'Proponer categoría' });
await btn.click(); await as.waitForTimeout(800);
console.log('vacía ->', (await d.innerText()).split('\n').filter((l) => /obligat|complet|requer|nombre/i.test(l)).join(' / '), as.audit.lastNative || '');
console.log('dialogos abiertos', await as.locator('dialog[open]').count()); const name = as.locator('#cl-name');
await name.fill('Iluminación LED ' + TAG);
const desc = as.locator('#cl-description'); if (await desc.count()) await desc.fill('Bombillos, paneles y tiras LED para uso residencial.');
const sw = d.locator('[aria-label*="erde"], [title*="erde"], [data-color]').nth(1); console.log('color elegido', await sw.getAttribute('aria-label').catch(()=>'?'), await sw.getAttribute('data-color').catch(()=>'?')); await sw.click().catch(()=>{});
const ic = d.locator('[data-icon]').nth(2); console.log('icono elegido', await ic.getAttribute('data-icon').catch(()=>'?'), await ic.getAttribute('aria-label').catch(()=>'?')); await ic.click().catch(()=>{});
await shot(as, 'nueva_llena', d);
await btn.click(); await as.waitForTimeout(1500);
console.log('guardar ->', await d.isVisible(), flushErrors(as, A).map((x) => x.slice(0, 160)));
const ad = await login('admin', OUT);
await go(ad, '/categories?approval_status=pending');
const row = ad.locator('tbody tr, [class*=card]', { hasText: 'LED ' + TAG }).first();
console.log('fila admin:', (await row.innerText()).replace(/\s+/g, ' '));
await shot(ad, 'pendiente_admin');
await row.locator('button').first().click(); await ad.waitForTimeout(1200);
const det = ad.locator('dialog[open]').last();
console.log('DETALLE:', (await det.innerText()).replace(/\n+/g, ' | ').slice(0, 1200));
await shot(ad, 'detalle', det);
const ap = det.getByRole('button', { name: 'Aprobar' });
if (await ap.count()) { await ap.click(); await ad.waitForTimeout(1500); console.log('aprobada', flushErrors(ad, A)); }
// Desactivar categoría con productos activos
await go(ad, '/categories');
const r2 = ad.locator('tbody tr', { hasText: 'E2E Ferretería' }).first();
console.log('acciones E2E Ferretería:', await r2.locator('button, a').evaluateAll((b) => b.map((x) => x.getAttribute('aria-label') || x.textContent.trim())));
await stop(OUT);
